# Reasons Razorpay documents as risk, compliance or merchant-side integration
# failures. Re-presenting one of these is not merely wasteful: programmatically
# retrying a risk-declined payment is the behaviour that gets a merchant's MID
# reviewed. agent/policy.py treats this set as a hard veto that the model cannot
# talk its way past.
NEVER_RETRY: frozenset[str] = frozenset(
    r for r, d in RULEBOOK.items() if d.recovery_class in ("hard_stop", "merchant_fix")
)

# Razorpay documents this reason as carrying no specific gateway error code, so
# the string alone cannot tell you what went wrong. The right action has to be
# inferred from context: method, issuer health, amount, customer history.
AMBIGUOUS: frozenset[str] = frozenset({"payment_failed"})


def documented_class(reason: str) -> str | None:
    """The recovery class Razorpay's docs imply, or None if unmapped.

    `None` is the interesting case. It means either a reason our rulebook has
    not caught up with, or one Razorpay documents ambiguously. Either way the
    agent is on its own.
    """
    entry = RULEBOOK.get(reason)
    return entry.recovery_class if entry else None


def describe(reason: str) -> str:
    """Razorpay's own description, for feeding to a model. Falls back to the
    raw reason string when we have no entry -- which is precisely when the
    model has to work hardest."""
    entry = RULEBOOK.get(reason)
    return entry.description if entry else f"(undocumented reason: {reason})"


KNOWN_REASONS: frozenset[str] = frozenset(RULEBOOK)
