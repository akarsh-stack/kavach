"""The merchant's rulebook, derived from Razorpay's public error documentation.

GENERATED BY scripts/gen_knowledge.py -- DO NOT EDIT BY HAND.

Source: https://razorpay.com/docs/errors/payments/list/

This is what any Razorpay merchant can look up. It carries each documented
failure reason, Razorpay's own description, Razorpay's own recommended next
step, and the recovery class those next steps imply.

Two things are deliberately absent:

  * **No recovery probabilities.** Razorpay does not publish them and neither do
    we. The agent has to form its own view of how likely a recovery is.

  * **No entry for 10 of the reasons that occur in production.** A real
    rulebook always lags -- gateway reason strings show up faster than anyone
    maps them. When the agent meets one of these it gets `None` from
    `documented_class()` and has to reason from the description text alone.
    This is the generalisation test, and it is where a language model has to
    earn its place over a lookup table.

The rules-engine baseline in evaluation/baselines.py is built from exactly this
file, so the comparison is fair: both policies get the public documentation, and
neither gets the answer key.
"""

